/** 대본을 평평한 줄 목록으로 — TTS·자막·슬라이드가 같은 배열을 본다. */
export function flatten(scenes = SCENES) {
  const out = [];
  scenes.forEach((scene, si) => {
    scene.lines.forEach((raw, li) => {
      const line = typeof raw === 'string' ? { say: raw } : raw;
      out.push({
        idx: out.length,
        sceneIndex: si,
        chapter: scene.chapter,
        chapterStart: li === 0,
        shot: scene.shot,
        say: line.say,
        text: line.text ?? line.say,
        focus: line.focus ?? null,
      });
    });
  });
  return out;
}
